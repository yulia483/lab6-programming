"""
Написать программу, которая:
1. Создаёт список из N случайных чисел
2. Находит сумму, среднее, минимум, максимум
3. Сортирует список
4. Удаляет дубликаты (сохраняя порядок)
"""

import random

# Ввод количества элементов
n = int(input("Введите N: "))
# Создание списка из N случайных чисел от 1 до 100
a = [random.randint(1, 100) for _ in range(n)]
# Вывод исходного списка
print(f"Исходный список: {a}")
# Сумма, среднее, минимум, максимум
s = sum(a)
avg = s / len(a)
mn = min(a)
mx = max(a)
print(f"Сумма: {s}")
print(f"Среднее: {avg:.2f}")
print(f"Минимум: {mn}")
print(f"Максимум: {mx}")
# Сортировка списка
a.sort()
print(f"Отсортированный: {a}")
# Удаление дубликатов с сохранением порядка
# dict.fromkeys(a) создаёт словарь, где ключи — это элементы списка (дубликаты убираются),
# а list() превращает ключи обратно в список
b = list(dict.fromkeys(a))
print(f"Без дубликатов: {b}")
