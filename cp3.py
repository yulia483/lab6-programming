"""
Реализовать алгоритм бинарного поиска в
отсортированном списке.
"""

print('введите сортированный список через пробел')
a=[int(x) for x in input().split()]
print('введите число,которое надо найти')
b=int(input())
#левая граница начало 
l=0
#правая граница конец
r=len(a)-1
#изначально считаем, что число не найдено
f=False
#запускаем цикл пока границы не пересеклись
while l<=r:
    m=(l+r)//2
    if a[m]==b:
        f=True
        break
    #если элемент больше, сдвигаем правую границу влево
    elif a[m]>b:
        r=m-1
    #иначе сдвигаем левую границу вправо
    else:
        l=m+1
if f:
    print(f"число {b} найдено")
else:
    print(f"число {b} не найдено")

