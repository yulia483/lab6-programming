"""
Транспонировать матрицу
(поменять строки и столбцы местами)
"""
# Исходная матрица 3x3
a = [
    [1, 2, 3],
    [4, 5, 6],
    [7, 8, 9]
]

# Транспонирование: zip(*a) "распаковывает" строки и собирает их в столбцы
b = [list(r) for r in zip(*a)]

print("Исходная матрица:")
for r in a:
    print(r)

print("\nТранспонированная матрица:")
for r in b:
    print(r)