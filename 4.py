"""
 Создать список студентов (имя, возраст, средний балл). Найти:
• Самого старшего • С самым высоким баллом • Средний возраст
"""

a = [("Иван", 25, 4.5), ("Мария", 22, 4.8), ("Пётр", 30, 4.2), ("Анна", 20, 4.9)]

# Самый старший (максимум по индексу 1)
old = max(a, key=lambda x: x[1])
print(f"Самый старший: {old[0]}, возраст {old[1]} лет")
# С самым высоким баллом (максимум по индексу 2)
best = max(a, key=lambda x: x[2])
print(f"Лучший студент: {best[0]}, балл {best[2]}")
# Средний возраст
avg_age = sum(x[1] for x in a) / len(a)
print(f"Средний возраст: {avg_age:.1f}")
# Сортировка по баллу (по убыванию)
srt = sorted(a, key=lambda x: x[2], reverse=True)
print("\nПо баллу (убывание):")
for name, age, gpa in srt:
    print(f"{name}: {gpa}")
