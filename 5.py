"""
Задача: Даны два списка. Найти:
Объединение (все элементы без дубликатов)
Пересечение (общие элементы)
Разность (элементы первого, которых нет во втором)
"""
# Ввод первого списка
# split() разбивает строку по пробелам, int(x) превращает в числа
print("Введите числа для первого списка через пробел:")
a = [int(x) for x in input().split()]
# Ввод второго списка
print("Введите числа для второго списка через пробел:")
b = [int(x) for x in input().split()]
# Превращаем списки в множества (set) для математических операций
s1 = set(a)
s2 = set(b)
u = s1 | s2       
i = s1 & s2       
d = s1 - s2      
# sorted() нужен, чтобы числа выводились по порядку (от меньшего к большему)
print(f"\nОбъединение: {sorted(u)}")
print(f"Пересечение: {sorted(i)}")
print(f"Разность: {sorted(d)}")
